'use strict';
const assert = require('node:assert/strict');
const fs = require('node:fs');
const tv = fs.readFileSync('public/tv.html', 'utf8');
const soundStart = tv.indexOf('const Sound =');
const soundEnd = tv.indexOf('const Caller =', soundStart);
const landStart = tv.indexOf('function land(fl, now)');
const landEnd = tv.indexOf('/* =====================================================================', landStart + 20);
assert(soundStart >= 0 && landStart >= 0, 'TV sound and landing modules exist');
const sound = tv.slice(soundStart, soundEnd);
const landing = tv.slice(landStart, landEnd);
assert.match(sound, /function boardThud\(strength = 1\)/, 'Immediate thud generator exists');
assert.match(sound, /return \{ init, play, boardThud,/, 'Thud exported by sound module');
assert.match(landing, /else \{\s*Sound\.boardThud\(/, 'Thud on any normal board hit, not only doubles');
assert.match(landing, /Sound\.play\('impact_board_'/, 'Original impact recordings remain in use');
assert.doesNotMatch(landing.slice(0, landing.indexOf('} else {\n    Sound.boardThud')), /boardThud\(/, 'Misses and bounce-outs do not get board thuds');
assert.match(tv, /Contact shadow anchors the steel point/, 'Stuck dart contact shadow retained');
assert.match(tv, /Brushed-metal glint/, 'Stuck dart barrel/point details retained');
assert.match(tv, /Slim specular line/, 'Flying dart steel highlight retained');
console.log('OCHE dart impact and rendering source checks passed');
